const citySelectEl = document.querySelector('.calculator .select select')
const squareInputEl = document.getElementById('square-value')
const squareRangeEl = document.getElementById('square-range')

function squareRangeOnChange(e) {
    squareValueEl.value = e.target.value;
}

function squareValueOnChange(e) {
    let value = Math.max(squareRangeEl.min, Math.min(squareRangeEl.max, e.target.value));
    squareRangeEl.value = value;
    squareInputEl.value = value;
}

const locationsEl = document.getElementById("result-locations")
const createdAtEl = document.getElementById("result-createdAt")
const investAllEl = document.getElementById("result-invest-all")
const investMeterEl= document.getElementById("result-invest-meter")
const paybackEl = document.getElementById("result-payback")
const roiEl = document.getElementById("result-roi")
const revenueEl = document.getElementById("result-revenue")
const expensesEl = document.getElementById("result-expenses")

// Функция для форматирования чисел (добавление пробелов и ₽)
function formatNumber(num, isCurrency = true) {
    // Для целых чисел
    if (Number.isInteger(num)) {
        return isCurrency 
            ? num.toString().replace(/\B(?=(\d{3})+(?!\d))/g, ' ') + ' ₽'
            : num.toString().replace(/\B(?=(\d{3})+(?!\d))/g, ' ');
    }
    // Для чисел с плавающей точкой
    const formatted = num.toFixed(2).replace(/\B(?=(\d{3})+(?!\d))/g, ' ');
    return isCurrency ? formatted + ' ₽' : formatted;
}

// Функция для форматирования ROI в проценты
function formatROI(roi) {
    return (roi * 100).toFixed(2) + '%';
}

// Функция обновления данных на странице
function updateResults() {
    const city = citySelectEl.value || "Москва";
    const square = parseInt(squareInputEl.value);
    
    // Получаем данные для выбранного города и площади
    const cityData = data[city];
    const squareData = cityData[square];
    
    if (!squareData) {
        console.error('Данные не найдены для выбранных параметров');
        return;
    }
    
    // Обновляем элементы DOM
    locationsEl.textContent = squareData.locations;
    createdAtEl.textContent = squareData.createdAt;
    investAllEl.textContent = formatNumber(squareData.investLocationSize);
    investMeterEl.textContent = formatNumber(squareData.investLocationMeter);
    paybackEl.textContent = squareData.paybackPeriod.toFixed(1) + ' мес';
    roiEl.textContent = formatROI(squareData.roi);
    revenueEl.textContent = formatNumber(squareData.revenue);
    expensesEl.textContent = formatNumber(squareData.expenses);
}

// Обработчики событий
function squareRangeOnChange(event) {
    const value = event.target.value;
    squareInputEl.value = value;
    squareRangeEl.value = value;
    updateResults();
}

function squareValueOnChange(event) {
    const value = event.target.value;
    // Проверяем, что значение находится в допустимом диапазоне
    if (value >= 1000 && value <= 5000 && value % 500 === 0) {
        squareRangeEl.value = value;
        updateResults();
    } else {
        // Если значение некорректное, возвращаем предыдущее
        event.target.value = squareRangeEl.value;
    }
}

citySelectEl.addEventListener('change', updateResults);

// Инициализация при загрузке страницы
document.addEventListener('DOMContentLoaded', function() {
    // Рендерим города
    const cities = Object.keys(data)
    cities.forEach(city => {
        const option = this.createElement('option')
        option.value = city
        option.innerHTML = city
        citySelectEl.appendChild(option)
    })

    // Устанавливаем начальные значения
    citySelectEl.value = "Москва";
    squareInputEl.value = "2500";
    squareRangeEl.value = "2500";
    
    // Обновляем данные
    updateResults();
    
    // Назначаем обработчики событий
    squareRangeEl.addEventListener('input', squareRangeOnChange);
    squareInputEl.addEventListener('input', squareValueOnChange);
});